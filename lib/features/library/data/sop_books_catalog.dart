  /// Find books matching a search query across title, series, or description
  static List<Book> searchBooks(String query) {
    if (query.trim().isEmpty) return allSopBooks;
    final lower = query.toLowerCase().trim();
    return allSopBooks.where((book) {
      return book.title.toLowerCase().contains(lower) ||
          (book.series?.toLowerCase().contains(lower) ?? false) ||
          book.description.toLowerCase().contains(lower);
    }).toList();
  }

  /// Filter books by thematic series
  static List<Book> filterBySeries(String seriesName) {
    if (seriesName == 'All Series' || seriesName.isEmpty) {
      return allSopBooks;
    }
    return allSopBooks.where((b) => b.series == seriesName).toList();
  }
